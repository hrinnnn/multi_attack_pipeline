def sensitive_tool_find(path: str, name_pattern: str):
    """
    The vulnerable tool exposed to the LLM.
    It constructs a shell command using f-string concatenation.
    """
    # VULNERABILITY: 
    # The 'path' argument is directly formatted into the shell string.
    # An attacker can inject flags like '-exec' by including spaces in the path string.
    # e.g., path = ". -exec id ;"
    
    # Construct command
    # NOTE: We use shell=True which makes this specific injection possible easily.
    command_str = f"find {path} -name '{name_pattern}'"
    
    print(f"\n[*] Agent is executing system command: {command_str}")
    print("-" * 40)
    
    try:
        # Execute
        # Ensure shell=True to allow argument injection to spawn subcommands
        output = subprocess.check_output(command_str, shell=True, stderr=subprocess.STDOUT)
        print("Command Output:")
        print(output.decode('utf-8'))
    except subprocess.CalledProcessError as e:
        print("Command Failed:")
        print(e.output.decode('utf-8'))
    print("-" * 40)
    print("[*] Execution finished.")

def main():
    print("==================================================================")
    print("   Chain #5: Pre-authorized Command Parameter Injection Simulator ")
    print("==================================================================\n")
    
    print("This script simulates an AI Agent receiving a tool call from an LLM.")
    print("Please paste the JSON tool call generated by Qwen-chat below.")
    print("Example format:")
    print('{"tool": "find_files", "parameters": {"path": "/tmp", "pattern": "*.txt"}}')
    print("-" * 60)
    
    try:
        user_input_str = input("Paste JSON here: ").strip()
        data = json.loads(user_input_str)
        
        tool_name = data.get("tool")
        params = data.get("parameters", {})
        
        if tool_name == "find_files":
            path = params.get("path", ".")
            pattern = params.get("pattern", "*")
            sensitive_tool_find(path, pattern)
        else:
            print(f"Unknown tool: {tool_name}")
            
    except json.JSONDecodeError:
        print("Invalid JSON format.")
    except Exception as e:
        print(f"An error occurred: {e}")

if __name__ == "__main__":
    main()
